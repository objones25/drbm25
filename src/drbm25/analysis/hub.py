"""Upload the rewrite sampling database and its metrics to a private Hugging Face dataset repo, verified.

CLI: ``python -m drbm25.analysis.hub --db DIR --metrics DIR --repo OWNER/NAME``.

Every file is committed in one commit, then downloaded back at that commit and compared by sha256 and size with
the local copy. ``<db>/UPLOADED.json`` (repo, commit, per-file hashes) is written only after every file matched,
so its presence means the Hub holds exactly this database.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import tempfile
import time
from collections import defaultdict
from collections.abc import Sequence
from dataclasses import asdict, fields
from pathlib import Path
from typing import Any, Final

from huggingface_hub import CommitOperationAdd, HfApi

from drbm25.eval.sample_db import SampleRow, read_db
from drbm25.obs import configure
from drbm25.publish import _with_retries, check_write_access, digest

logger = logging.getLogger(__name__)

MARKER: Final = "UPLOADED.json"
REPO_TYPE: Final = "dataset"


def _local_files(db: Path, metrics: Path) -> dict[str, Path]:
    """Repo path -> local file: the db shards (not their success markers or an old UPLOADED.json) and every
    metrics output (not the report scratch dir)."""
    files = {f"db/{p.relative_to(db).as_posix()}": p for p in sorted(db.glob("*/shard-*.parquet"))}
    files |= {f"metrics/{p.name}": p for p in sorted(metrics.iterdir()) if p.is_file()}
    return files


def dataset_card(rows: Sequence[SampleRow], *, repo_id: str) -> str:
    by_source: dict[str, list[SampleRow]] = defaultdict(list)
    for r in rows:
        by_source[r.source].append(r)
    source_lines = []
    for source, rs in sorted(by_source.items()):
        n_queries = len({r.qid for r in rs})
        models = sorted({f"{r.model_id}@{r.model_revision}" for r in rs if r.model_id})
        model = ", ".join(models) if models else "none (the raw dev query)"
        source_lines.append(f"| {source} | {len(rs)} | {n_queries} | {model} |")
    schema = "\n".join(f"| {f.name} | {f.type} |" for f in fields(SampleRow))
    return f"""---
license: other
pretty_name: DeepRetrieval BM25 query rewrites (sampled)
tags:
- query-rewriting
- information-retrieval
- reinforcement-learning
---

# {repo_id}

Sampled query rewrites of the MS MARCO-Science dev queries (DeepRetrieval data) from Qwen2.5-3B-Instruct, before
and after PPO training with a BM25 nDCG@10 reward (standard vs count-once BM25). One row per sampled response:
the reasoning (`think_text`), the rewrite, its analyzed terms, the top-10 documents and nDCG@10 under both BM25
scorers. Sampling used the training settings (temperature 0.6, top-p 1, no top-k, 350 new tokens); every policy
used the same seeds for the same query, and `seed` is the seed each sample was drawn with.

## Sources

| source | rows | queries | model |
|---|---|---|---|
{chr(10).join(source_lines)}

`db/<source>/shard-*.parquet` holds the rows; `metrics/` holds the behavior metrics computed from them
(per sample, per query, policy comparisons, vocabulary statistics).

## Schema

| column | type |
|---|---|
{schema}

## License

`license: other`: the rewrites were generated by Qwen2.5-3B-Instruct (Qwen license) and its fine-tunes, from
queries of MS MARCO (non-commercial research terms) via DeepRetrieval. Check both before reuse.
"""


def upload_database(
    db: Path, metrics: Path, *, repo_id: str, api: Any = None, sleep: Any = time.sleep
) -> dict[str, Any]:
    """Commit the database, metrics and a dataset card to ``repo_id`` (private), verify every file by downloading
    it back, then write ``<db>/UPLOADED.json``; returns the marker. Raises RuntimeError on any mismatch."""
    api = api or HfApi()
    rows = read_db(db)
    if not rows:
        raise ValueError(f"no rows in {db}")
    owner = check_write_access(_with_retries(api.whoami, sleep=sleep))
    if repo_id.split("/", 1)[0] != owner:
        raise ValueError(f"repo {repo_id} is not under the token owner's namespace {owner!r}")
    (db / MARKER).unlink(missing_ok=True)
    files = _local_files(db, metrics)
    with tempfile.TemporaryDirectory() as tmp:
        card = Path(tmp) / "README.md"
        card.write_text(dataset_card(rows, repo_id=repo_id), encoding="utf-8")
        files["README.md"] = card
        digests = {path: digest(local) for path, local in files.items()}
        _with_retries(lambda: api.create_repo(repo_id, repo_type=REPO_TYPE, private=True, exist_ok=True), sleep=sleep)
        ops = [CommitOperationAdd(path_in_repo=p, path_or_fileobj=str(local)) for p, local in files.items()]
        commit = api.create_commit(repo_id, ops, commit_message="Upload rewrite sampling database", repo_type=REPO_TYPE)
        revision = commit.oid
        logger.info("committed %d files to %s at %s; verifying", len(files), repo_id, revision)
        problems = []
        for path, want in sorted(digests.items()):
            with tempfile.TemporaryDirectory(dir=tmp) as dl:
                got_path = _with_retries(
                    lambda p=path, d=dl: api.hf_hub_download(
                        repo_id, p, repo_type=REPO_TYPE, revision=revision, local_dir=d, force_download=True
                    ),
                    sleep=sleep,
                )
                got = digest(Path(got_path))
            if (got.sha256, got.size) != (want.sha256, want.size):
                problems.append(f"{path}: Hub copy {got.sha256}/{got.size} != local {want.sha256}/{want.size}")
    if problems:
        raise RuntimeError("upload verification failed: " + "; ".join(problems))
    marker = {
        "repo_id": repo_id,
        "repo_type": REPO_TYPE,
        "commit": revision,
        "files": {path: asdict(d) for path, d in sorted(digests.items())},
    }
    tmp_marker = db / f"{MARKER}.tmp"
    tmp_marker.write_text(json.dumps(marker, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp_marker, db / MARKER)
    logger.info("verified all %d files on %s; wrote %s", len(digests), repo_id, db / MARKER)
    return marker


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Upload and verify the rewrite sampling database on the Hub.")
    parser.add_argument("--db", type=Path, required=True)
    parser.add_argument("--metrics", type=Path, required=True)
    parser.add_argument("--repo", required=True)
    ns = parser.parse_args(argv)
    configure(level="INFO", fmt="json")
    upload_database(ns.db, ns.metrics, repo_id=ns.repo)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
